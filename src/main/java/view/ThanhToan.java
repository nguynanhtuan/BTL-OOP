    public ThanhToan(java.awt.Frame parent, boolean modal, Phone phone) {
        super(parent, modal);
        initComponents(); // Hàm sinh giao diện tự động của NetBeans
        
        this.setLocationRelativeTo(parent); // Căn giữa cửa sổ
        this.phone = phone;

        // 1. Tính toán phí dịch vụ 1%
        double phiDichVu = phone.getPrice() * 0.01;
        lblSoTien.setText("Số tiền cần chuyển: " + String.format("%,.0f VNĐ", phiDichVu));

        // 2. Load hình ảnh mã QR từ thư mục images
        try {
            // Thay đổi "qr_admin.jpg" thành tên file ảnh QR thực tế của bạn
            File file = new File("images/qr_admin.jpg"); 
            if (file.exists()) {
                // Thu phóng ảnh cho vừa vặn với kích thước JLabel (ví dụ: 200x200)
                Image img = new ImageIcon(file.getAbsolutePath()).getImage().getScaledInstance(200, 200, Image.SCALE_SMOOTH);
                lblQRCode.setIcon(new ImageIcon(img));
                lblQRCode.setText(""); // Xóa text mặc định nếu có ảnh
            } else {
                lblQRCode.setText("Chưa cấu hình ảnh QR");
                lblQRCode.setHorizontalAlignment(javax.swing.SwingConstants.CENTER);
            }
        } catch (Exception e) {
            e.printStackTrace();
            lblQRCode.setText("Lỗi hiển thị QR");
        }
    }

