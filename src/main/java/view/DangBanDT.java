    private void Nut_Luu_ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Nut_Luu_ActionPerformed
                                                   
        String tenMay = jTextField1.getText().trim();
        String hang = jComboBox1.getSelectedItem().toString();
        String giaStr = jTextField2.getText().trim();
        String moTa = jTextArea1.getText().trim();
        String videoLink = jTextArea2.getText().trim();
        
        if (tenMay.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Vui lòng nhập tên máy!");
            return;
        }
        if (giaStr.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Vui lòng nhập giá bán!");
            return;
        }
        if (jComboBox1.getSelectedItem() == null || jComboBox1.getSelectedItem().toString().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Vui lòng chọn hãng điện thoại!");
            return;
        }
        if (moTa.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Vui lòng nhập mô tả sản phẩm!");
            return;
        }
        if (selectedImageFile == null || imagePath.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Vui lòng chọn ảnh điện thoại!");
            return;
        }
        if (videoLink.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Vui lòng nhập link video!");
            return;
        }
        if (currentUser == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Không tìm thấy thông tin người dùng đăng nhập!");
            return;
        }

        try {
            double gia = Double.parseDouble(giaStr);
            if (gia <= 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Giá tiền phải lớn hơn 0!");
            return;
        }
            // --- BẮT ĐẦU ĐOẠN CODE COPY ẢNH VÀO PROJECT ---
            if (selectedImageFile != null) {
                // 1. Tạo thư mục 'images' nếu chưa có
                java.io.File thuMucImages = new java.io.File("images");
                if (!thuMucImages.exists()) {
                    thuMucImages.mkdirs(); 
                }
                
                // 2. Copy file từ ổ D sang thư mục images của project
                java.io.File dich = new java.io.File(thuMucImages, imagePath);
                java.nio.file.Files.copy(
                    selectedImageFile.toPath(), 
                    dich.toPath(), 
                    java.nio.file.StandardCopyOption.REPLACE_EXISTING
                );
                System.out.println("Đã copy ảnh vào: " + dich.getAbsolutePath());
            }
            // --- KẾT THÚC ĐOẠN CODE COPY ẢNH ---

            model.Phone phone = new model.Phone();
            phone.setName(tenMay);
            phone.setBrand(hang);
            phone.setPrice(gia);
            phone.setDescription(moTa);
            
            phone.setImagePath(imagePath);   
            phone.setVideoPath(videoLink);
            phone.setUserId(currentUser.getId());
            phone.setStatus("PENDING");      
               System.out.println("USER ID HIỆN TẠI LÀ: " + currentUser.getId());
            dao.PhoneDAO phoneDAO = new dao.PhoneDAO();
            boolean success = phoneDAO.insert(phone); 

            if (success) {
                javax.swing.JOptionPane.showMessageDialog(this, "Đăng bán thành công! Vui lòng chờ Admin duyệt.");
                this.dispose(); 
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Đăng bán thất bại! Vui lòng thử lại.");
            }

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Giá tiền phải là một số hợp lệ (VD: 15000000)!");
        } catch (Exception e) {
            e.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Lỗi hệ thống: " + e.getMessage());
        }
    }//GEN-LAST:event_Nut_Luu_ActionPerformed

